List<MenuItemModel> getAllSampleProducts() {
  final all = <MenuItemModel>[];
  for (final list in sampleConstructionProducts().values) {
    all.addAll(list);
  }
  return all;
}

List<MenuItemModel> getSampleProductsByCategory(String categoryName) {
  final norm = categoryName.trim().toLowerCase();
  return getAllSampleProducts().where((p) {
    final cat = p.category.toLowerCase();
    if (cat == norm) return true;
    if (norm.contains('cement') && cat.contains('cement')) return true;
    if (norm.contains('steel') && cat.contains('steel')) return true;
    if (norm.contains('brick') && cat.contains('brick')) return true;
    if (norm.contains('sand') && cat.contains('sand')) return true;
    if (norm.contains('plumb') && cat.contains('plumb')) return true;
    if (norm.contains('paint') && cat.contains('paint')) return true;
    if (norm.contains('elect') && cat.contains('elect')) return true;
    if (norm.contains('hard') && cat.contains('hard')) return true;
    if (norm.contains('water') && cat.contains('water')) return true;
    return false;
  }).toList();
}

MenuItemModel? getSampleProductById(String id) {
  for (final p in getAllSampleProducts()) {
    if (p.id == id) return p;
  }
  return null;
}
